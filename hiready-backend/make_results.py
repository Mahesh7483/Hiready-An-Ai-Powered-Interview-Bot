# ---------------------------------------------------------------- provenance
# Latency and throughput numbers are only comparable across experiments if they
# came from the same machine. Mixing hosts silently is an easy mistake to make
# and an awkward one to explain to a reviewer, so check it here.
hosts, models = {}, {}
for name in sorted(REQUIRED):
    p = OUT / f"{name}.json"
    if not p.exists():
        continue
    prov = json.loads(p.read_text(encoding="utf-8")).get("provenance", {})
    if prov.get("platform"):
        hosts.setdefault(prov["platform"], []).append(name)
    if prov.get("groqModel"):
        models.setdefault(prov["groqModel"], []).append(name)

if len(hosts) > 1:
    print("\nWARNING - results came from more than one machine:")
    for host, names in hosts.items():
        print(f"  {host}: {', '.join(names)}")
    print("  Latency figures from different hosts are not comparable. Delete the")
    print("  odd ones out of experiments/out/ and re-run them on one machine.")

if len(models) > 1:
    print("\nWARNING - results came from more than one model:")
    for model, names in models.items():
        print(f"  {model}: {', '.join(names)}")
