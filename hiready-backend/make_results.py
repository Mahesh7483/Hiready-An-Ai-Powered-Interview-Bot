def wilson(successes, n, z=1.96):
    """Wilson score interval, matching the harness's own estimator."""
    if not n:
        return {"n": 0, "p": None, "lo": None, "hi": None}
    p = successes / n
    d = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / d
    half = (z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5)) / d
    return {"n": n, "p": p, "lo": max(0.0, centre - half), "hi": min(1.0, centre + half)}


