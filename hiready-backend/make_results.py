def load(name):
    p = OUT / f"{name}.json"
    if not p.exists():
        (missing if name in REQUIRED else optional_missing).append(name)
        return None
    return json.loads(p.read_text(encoding="utf-8"))


def pct(x, d=1):
    return PENDING if x is None else f"{x * 100:.{d}f}"


def val(x, d=2):
    return PENDING if x is None else f"{x:.{d}f}"


def ci(w):
    """Format a Wilson interval as 'p [lo, hi]' in percentage points."""
    if not w or w.get("p") is None:
        return PENDING
    return f"{w['p']*100:.1f} [{w['lo']*100:.1f}, {w['hi']*100:.1f}]"


